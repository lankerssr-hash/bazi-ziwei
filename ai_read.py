def load_config():
    cfg = {"provider": "deepseek"}
    try:
        with io.open(CFG, "r", encoding="utf-8") as f:
            cfg.update(json.load(f))
    except Exception:
        pass
    p = cfg.get("provider", "deepseek")
    base = dict(PRESETS.get(p, PRESETS["deepseek"]))
    # custom 里可以覆盖
    for k in ("url", "model", "key_file", "max_tokens"):
        if cfg.get(k):
            base[k] = cfg[k]
        c = cfg.get("custom") or {}
        if c.get(k):
            base[k] = c[k]
    base["provider"] = p
    return base


def save_config(provider, **kw):
    cfg = {"provider": provider}
    cfg.update({k: v for k, v in kw.items() if v})
    with io.open(CFG, "w", encoding="utf-8") as f:
        json.dump(cfg, f, ensure_ascii=False, indent=1)


def _key(path):
    """优先读环境变量 DS_PROXY_KEY（里面放密钥本身），否则读文件。"""
    env = _os.environ.get("DS_PROXY_KEY", "").strip()
    if env:
        return env
    try:
        with io.open(path, "r", encoding="utf-8") as f:
            return f.read().strip()
    except Exception:
        return ""


