def clause_violations(text, min_len=5):
    """找出少于 min_len 个汉字的分句（只按 ，。； 切，不算顿号）"""
    import re
    t = re.sub(r"[*#>`|]+", "", text)
    parts = re.split(r"[，。；,;]", t)
    bad = []
    for p in parts:
        seg = p.strip()
        if not seg:
            continue
        n = len(re.findall(r"[\u4e00-\u9fff]", seg))
        if 0 < n < min_len:
            bad.append(seg)
    return bad


def ask(prompt_text, on_done, on_fail, box=None, prompt=None):
    """后台线程请求。box 是个 dict，线程只往里写结果，界面由主线程轮询。"""
    def work():
        _dbg2("线程启动")
        def put(k, v):
            _dbg2("put %s (%d 字)" % (k, len(str(v))))
            if box is not None:
                box[k] = v
                _dbg2("box 现在 keys=%s" % list(box.keys()))

        _dbg2("读配置")
        cfg = load_config()
        _dbg2("配置: %s" % cfg.get("url"))
        key = _key(cfg["key_file"])
        _dbg2("key 长度: %d" % len(key))
        if not key:
            put("fail", "找不到 key：%s\n\n当前上游：%s\n%s"
                % (cfg["key_file"], cfg["name"], cfg["note"]))
            return
        url = cfg["url"]
        if not url:
            put("fail", "上游地址是空的，去 ai_config.json 里填")
            return

        def _request(sys_prompt, user_text, mt):
            body = json.dumps({
                "model": cfg["model"],
                "messages": [
                    {"role": "system", "content": sys_prompt},
                    {"role": "user", "content": user_text},
                ],
                "max_tokens": mt,
                "temperature": 0.45,
                # ★ 关掉推理：实测 8.8 秒 → 1.0 秒
                **({"thinking": {"type": "disabled"},
                    "reasoning_effort": "none"}
                   if cfg.get("no_think", True) else {}),
            }, ensure_ascii=False).encode("utf-8")
            req = urllib.request.Request(
                url, data=body,
                headers={"Content-Type": "application/json",
                         "Authorization": "Bearer " + key})
            opener = urllib.request.build_opener(
                urllib.request.ProxyHandler({}))
            _dbg2("open 中")
            with opener.open(req, timeout=600) as r:
                d = json.loads(r.read().decode("utf-8"))
            _dbg2("拿到响应, keys=%s" % list(d.keys()))
            try:
                return (d.get("choices") or [{}])[0].get(
                    "message", {}).get("content") or ""
            except Exception as _e:
                _dbg2("解析异常: %r" % (_e,))
                return ""

        def _save(txt):
            try:
                io.open(os.path.join(HERE, "上次AI解盘.md"), "w",
                        encoding="utf-8").write(txt)
            except Exception:
                pass

        base_sys = (CLAUSE_RULE + "\n\n" + PRONOUN_RULE
                    + "\n\n" + (prompt or PROMPT))
        try:
            best = ""
            best_bad = 10 ** 6
            # 第一次正常写；断句违规太多，就带提醒重写一次
            for attempt, extra in enumerate(("", CLAUSE_RETRY2)):
                mt = cfg["max_tokens"]
                if attempt > 0:
                    mt = int(cfg["max_tokens"] * 4 // 3)
                _dbg2("第 %d 次请求 mt=%d" % (attempt + 1, mt))
                txt = _request(base_sys + extra, prompt_text, mt)
                if not txt.strip():
                    continue
                bad = clause_violations(txt)
                _dbg2("正文 %d 字，断句违规 %d 处" % (len(txt), len(bad)))
                if len(bad) < best_bad:
                    best, best_bad = txt, len(bad)
                if len(bad) <= 6:
                    break
            if best.strip():
                _save(best)
                if box is not None:
                    box["ok"] = best
                    box["bad_clauses"] = best_bad
                return
            put("fail", "模型返回空（推理吃光了 token）。再点一次。")
        except Exception as e:
            _dbg2("异常: %s: %s" % (type(e).__name__, e))
            put("fail", "%s: %s\n\n当前上游：%s" % (
                type(e).__name__, e, cfg["name"]))

    t = Thread(target=work, daemon=True)
    t.start()


